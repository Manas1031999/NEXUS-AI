package com.nexus.ai.service;

import com.nexus.ai.dto.AiResponse;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientException;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;
import java.util.Map;

@Service
public class GeminiService implements AiProvider {

    private final RestClient restClient;
    private final String model;
    private final String apiKey;

    public GeminiService(
            @Value("${nexus.ai.gemini.base-url}") String baseUrl,
            @Value("${nexus.ai.gemini.model}") String model,
            @Value("${nexus.ai.gemini.api-key}") String apiKey) {

        this.restClient = RestClient.create(baseUrl);
        this.model = model;
        this.apiKey = apiKey;
    }

    @Override
    public AiResponse generateResponse(String prompt) {

        Map<String, Object> request = Map.of(
                "contents", List.of(
                        Map.of(
                                "parts", List.of(
                                        Map.of("text", prompt)
                                )
                        )
                )
        );

        try {

            Map<?, ?> result = restClient.post()
                    .uri("/models/{model}:generateContent", model)
                    .header("x-goog-api-key", apiKey)
                    .body(request)
                    .retrieve()
                    .body(Map.class);

            if (result == null) {
                throw new ResponseStatusException(
                        HttpStatus.BAD_GATEWAY,
                        "Empty response received from Gemini"
                );
            }

            List<?> candidates = (List<?>) result.get("candidates");

            if (candidates == null || candidates.isEmpty()) {
                throw new ResponseStatusException(
                        HttpStatus.BAD_GATEWAY,
                        "No response generated by Gemini"
                );
            }

            Map<?, ?> candidate = (Map<?, ?>) candidates.get(0);
            Map<?, ?> content = (Map<?, ?>) candidate.get("content");
            List<?> parts = (List<?>) content.get("parts");
            Map<?, ?> firstPart = (Map<?, ?>) parts.get(0);

            String response = firstPart.get("text").toString();

            return new AiResponse(
                    "NEXUS AI",
                    getProviderName(),
                    model,
                    response,
                    "SUCCESS"
            );

        } catch (RestClientException ex) {

            throw new ResponseStatusException(
                    HttpStatus.BAD_GATEWAY,
                    "Unable to communicate with Gemini"
            );
        }
    }

    @Override
    public String getProviderName() {
        return "gemini";
    }
}